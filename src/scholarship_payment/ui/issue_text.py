def location_text(rows: tuple[int, ...], fields: tuple[str, ...], limit: int = 8) -> str:
    """행 번호(없으면 위치 이름)를 짧게. 값은 담지 않는다."""
    if rows:
        shown = ", ".join(str(r) for r in rows[:limit])
        more = len(rows) - limit
        return f"행 {shown}" + (f" 외 {more}건" if more > 0 else "")
    if fields:
        return "위치 " + ", ".join(fields[:limit])
    return ""
